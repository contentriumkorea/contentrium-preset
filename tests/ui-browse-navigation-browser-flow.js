async page => {
  if (!/^http:\/\/(127\.0\.0\.1|localhost):/.test(page.url())) throw Error('Standalone product UI only');
  const context=await page.context().browser().newContext({viewport:{width:1150,height:800}}), target=await context.newPage(), checks=[], failures=[], errors=[];
  const check=(ok,name)=>{checks.push({ok,name});if(!ok)failures.push(name);};
  target.on('pageerror',e=>errors.push(e.message));
  try {
    await target.goto(new URL('/',page.url()).href); await target.waitForFunction(()=>document.querySelectorAll('.preset-card').length===43);
    const card=target.locator('.preset-card[data-entry-id="9e5"]');
    await card.click({button:'right'});
    const focus=target.getByRole('menuitem',{name:'이 폴더에 집중',exact:true});
    check(await focus.count()===1,'item menu provides Focus Folder');
    if(failures.length)return{ok:false,checks,failures};
    await focus.click();
    const selected=await target.evaluate(()=>ContentriumUI.view.getState()), focused=selected.focusFolder;
    check(!!focused&&selected.category===focused,'Focus Folder retains existing outside-category fallback');
    check(await target.locator('[role=treeitem]').evaluateAll((nodes,key)=>nodes.every(n=>n.dataset.categoryKey===key||n.dataset.categoryKey.startsWith(key+' / ')),focused),'unrelated roots are hidden in focused tree');
    check(await target.locator('.preset-card').count()<43,'focused folder limits grid contents');
    await target.reload();await target.waitForFunction(()=>ContentriumUI.view&&ContentriumUI.view.getState().entries===43);
    check(await target.evaluate(key=>ContentriumUI.view.getState().focusFolder===key,focused),'focused folder survives panel reload');
    await target.getByRole('button',{name:'상위 폴더에 집중',exact:true}).click();
    check(await target.evaluate(key=>ContentriumUI.view.getState().focusFolder===key.split(' / ').slice(0,-1).join(' / '),focused),'focused parent expands one level');
    const focusedRoot=target.locator('[role=treeitem]').first();
    await focusedRoot.locator('.expand').click();
    check(await target.locator('[role=treeitem]').count()===1&&await focusedRoot.getAttribute('aria-expanded')==='false','focused root collapse matches its accessible state');
    await focusedRoot.focus();await focusedRoot.press('Enter');
    check(await target.locator('[role=treeitem]').count()>1&&await focusedRoot.getAttribute('aria-expanded')==='true','tree Enter toggles expansion without changing category');
    const categoryBeforeClear=await target.evaluate(()=>ContentriumUI.view.getState().category);
    await target.getByRole('button',{name:'모든 항목 표시',exact:true}).click();
    check(await target.evaluate(key=>ContentriumUI.view.getState().focusFolder===''&&ContentriumUI.view.getState().category===key,categoryBeforeClear),'Show all items restores roots while preserving valid category');
    const tree=target.locator('[role=treeitem]'), lastTree=await tree.last().getAttribute('data-category-key');
    await tree.first().focus();await tree.first().press('ArrowUp');
    check(await target.evaluate(key=>ContentriumUI.view.getState().category===key,lastTree)&&await target.locator('.preset-card').count()<43,'tree Up wraps and selects the last visible folder');
    await target.locator('[role=treeitem]:focus').press('Home');
    check(await target.locator('.preset-card').count()===43,'tree Home selects All items');
    const all=target.locator('.preset-card');await all.first().focus();await all.first().press('ArrowRight');
    check(await target.locator('.inline-variants').count()===0,'keyboard navigation leaves variants closed initially');
    await target.waitForTimeout(1100);
    check(await target.locator('.inline-variants').count()===1,'same keyboard-selected group opens after one second');
    await card.focus();await card.press('ArrowRight');await tree.first().click();await target.waitForTimeout(1100);
    check(await target.locator('.inline-variants').count()===0&&await target.locator('.preset-card.selected').count()===0,'tree selection cancels pending keyboard expansion and grid selection');
    await card.focus();await card.press('ArrowRight');await target.getByRole('searchbox',{name:'항목 검색'}).fill('no-match');
    await target.waitForTimeout(1100);
    check(await target.locator('.inline-variants').count()===0,'search invalidates a pending keyboard expansion');
    await target.getByRole('button',{name:'검색 지우기',exact:true}).click();
    await card.locator('.variant-button').click();
    await card.locator('.variant-row').filter({hasText:/Right/}).click();
    const before=await card.getAttribute('data-variant-id');
    await target.getByRole('searchbox',{name:'항목 검색'}).fill('Motion Left');await target.waitForFunction(()=>ContentriumUI.view.getState().query==='Motion Left');
    check(await card.getAttribute('data-variant-id')!==before,'filtered mode selects its own matching direction');
    await target.getByRole('button',{name:'검색 지우기',exact:true}).click();
    check(await card.getAttribute('data-variant-id')===before,'clearing search restores default direction memory');
    check(await card.locator('.inline-variants').count()===1&&await card.getAttribute('class').then(c=>c.includes('selected')),'clearing filters restores default selection and shared popup openness');
    await card.click({button:'right'});await target.keyboard.press('Escape');
    check(await card.evaluate(n=>document.activeElement===n),'Escape restores focus to the context menu owner');
    check(errors.length===0,'no browser script errors');
    return{ok:failures.length===0,checks,failures,scope:'standalone real UI/catalog; no native application'};
  } finally { await context.close(); }
}
